package day_5;

public class Pre_post_increment_decrement {

	public static void main(String[] args) {
		//post increment
		int a=0;
		
		a++;
		System.out.println(a);
		
		//post decrement
		a--;
		System.out.println(a);
		
		//pre increment
		int b=2;
		
		++b;
		System.out.println(b);
		
		//pre decrement
		--b;
		System.out.println(b);
		
	 

	}

}
